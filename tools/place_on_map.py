#!/usr/bin/env python3
"""Places every facility on assets/map.webp and writes data/map_xy.js (facility id -> [x, y] in image pixels).

Run from the project root after adding facilities:  python3 tools/place_on_map.py
Needs: pillow numpy scipy scikit-image

1. lat/lng -> pixel with a linear fit of the image (calibrated against state centres and district HQs).
2. A dot that lands on a border line, in the sea or in another state is moved to the nearest spot inside its own state.
3. Dots of one state keep a small gap so they do not stack.
"""
import json, re
import numpy as np
from PIL import Image
from scipy import ndimage as ndi
from scipy.spatial import cKDTree
from skimage import measure, morphology

IMG = 'assets/map.webp'
AX, BX, AY, BY = 37.043, -2431.89, -40.283, 1518.15      # x = AX*lng + BX,  y = AY*lat + BY
SEP = 8                                                  # minimum gap between dots of a state (pixels)

# a pixel inside each state's region (the region's centre as seen on the image)
SEEDS = {'RJ': [(304, 435)], 'MH': [(381, 731)], 'MP': [(464, 564)], 'UP': [(552, 424)], 'KA': [(381, 923)], 'AP': [(527, 893)],
         'GJ': [(220, 595)], 'OD': [(700, 702)], 'CG': [(610, 661)], 'TN': [(474, 1073)], 'TS': [(499, 796)], 'BR': [(737, 492)],
         'WB': [(827, 572)], 'AS': [(998, 468)], 'JH': [(737, 574)], 'UK': [(499, 289)], 'HP': [(431, 217)], 'PB': [(365, 262)],
         'HR': [(396, 333)], 'AR': [(1066, 395)], 'SK': [(843, 419)], 'NL': [(1061, 474)], 'MN': [(1044, 531)], 'MZ': [(1011, 592)],
         'TR': [(972, 575)], 'ML': [(947, 501)], 'KL': [(388, 1090)], 'GA': [(300, 891)], 'JK': [(352, 157)],
         'LA': [(460, 123), (352, 70)], 'DL': [(426, 359)]}
# states that have no region of their own on this map: use the neighbouring state(s) ...
SHARE = {'CH': ['PB', 'HR'], 'DN': ['GJ', 'MH'], 'PY': ['TN', 'AP']}
# ... or the island groups drawn in the corners (x0, y0, x1, y1)
ISLANDS = {'LD': (190, 1000, 275, 1165), 'AN': (1000, 895, 1085, 1195)}

rgba = np.array(Image.open(IMG).convert('RGBA')).astype(int)
fill = (rgba[..., 3] > 200) & (np.abs(rgba[..., :3] - [217, 218, 209]).sum(axis=2) < 40)
lab = measure.label(morphology.erosion(fill, morphology.disk(1)), connectivity=1)
dt = ndi.distance_transform_edt(lab > 0)
ys, xs = np.nonzero(lab)
near = cKDTree(np.c_[xs, ys])
label_of = lambda sx, sy: int(lab[ys[near.query((sx, sy))[1]], xs[near.query((sx, sy))[1]]])
REGION = {s: [label_of(*p) for p in ps] for s, ps in SEEDS.items()}

def target(state):
    """(candidate pixels as an Nx2 x,y array) for a state, kept away from border lines where the region is big enough."""
    if state in ISLANDS:
        x0, y0, x1, y1 = ISLANDS[state]
        m = np.zeros(rgba.shape[:2], bool); m[y0:y1, x0:x1] = rgba[y0:y1, x0:x1, 3] > 128
        return np.argwhere(m)[:, ::-1]
    labels = sum((REGION[s] for s in SHARE.get(state, [state])), [])
    m = np.isin(lab, labels)
    margin = min(5, 0.6 * dt[m].max())
    return np.argwhere(m & (dt >= margin))[:, ::-1]

facilities = []
for f in ('data/hospitals.js', 'data/sample_facilities.js'):
    facilities += [json.loads(l.strip().rstrip(',')) for l in open(f, encoding='utf-8') if l.startswith('{"id"')]

out, moved = {}, []
for state in sorted({f['st'] for f in facilities}):
    pts = target(state); tree = cKDTree(pts); placed = []
    for f in (f for f in facilities if f['st'] == state):
        p = (AX * f['lng'] + BX, AY * f['lat'] + BY)
        _, order = tree.query(p, k=min(len(pts), 600))
        order = np.atleast_1d(order)
        for sep in (SEP, SEP // 2, 0):
            pick = next((pts[i] for i in order if all(np.hypot(*(pts[i] - q)) >= sep for q in placed)), None)
            if pick is not None: break
        pick = pts[order[0]] if pick is None else pick
        placed.append(pick); out[f['id']] = [int(pick[0]), int(pick[1])]
        moved.append(np.hypot(pick[0] - p[0], pick[1] - p[1]))

ids = sorted(out)
body = ',\n'.join(','.join(f'{i}:[{out[i][0]},{out[i][1]}]' for i in ids[k:k + 8]) for k in range(0, len(ids), 8))
open('data/map_xy.js', 'w').write(f'/* GENERATED by tools/place_on_map.py: facility id -> [x, y] on assets/map.webp (1293 x 1217). */\nconst MAP_XY={{\n{body}\n}};\n')
print(len(out), 'facilities placed; median shift %.0f px, 90th percentile %.0f px, max %.0f px' % (np.median(moved), np.percentile(moved, 90), max(moved)))
